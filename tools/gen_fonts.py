#!/usr/bin/env python3
"""Render the Inter typeface into 1-bit bitmap fonts for the e-paper canvas.

Writes main/core/fonts.cpp. The generated file is committed, so building the
firmware does not need Python or Pillow; rerun this only to change the fonts.

    python3 tools/gen_fonts.py --font-dir /usr/share/fonts/opentype/inter
"""

import argparse
import pathlib

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7E

# (C++ name, font file, pixel size)
FONTS = [
    ("kFontSmall", "Inter-SemiBold.otf", 20),
    ("kFontMedium", "Inter-Bold.otf", 28),
    ("kFontLarge", "Inter-ExtraBold.otf", 44),
    ("kFontHuge", "Inter-Black.otf", 72),
]


def render_font(path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, bitmap = [], bytearray()

    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        left, _, right, _ = font.getbbox(ch)
        x0 = min(0, left)
        width = max(advance, right) - x0
        img = Image.new("L", (max(width, 1), height), 0)
        ImageDraw.Draw(img).text((-x0, 0), ch, font=font, fill=255)

        stride = (width + 7) // 8
        offset = len(bitmap)
        for y in range(height):
            for bx in range(stride):
                byte = 0
                for bit in range(8):
                    x = bx * 8 + bit
                    if x < width and img.getpixel((x, y)) >= 128:
                        byte |= 0x80 >> bit
                bitmap.append(byte)
        glyphs.append((offset, width, advance, x0))

    return height, ascent, glyphs, bitmap


def emit(name, file, size, height, ascent, glyphs, bitmap):
    out = [f"// {file} at {size}px: line height {height}, ascent {ascent}"]
    out.append(f"const uint8_t {name}Bits[] = {{")
    for i in range(0, len(bitmap), 24):
        out.append("    " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const Glyph {name}Glyphs[] = {{")
    for code, (offset, width, advance, x0) in zip(range(FIRST, LAST + 1), glyphs):
        label = chr(code).replace("\\", "backslash")
        out.append(f"    {{{offset}, {width}, {advance}, {x0}}},  // {label}")
    out.append("};")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--font-dir", default="/usr/share/fonts/opentype/inter")
    parser.add_argument("--out", default=str(pathlib.Path(__file__).resolve().parent.parent / "main/core/fonts.cpp"))
    args = parser.parse_args()

    parts = [
        "// Generated by tools/gen_fonts.py from the Inter typeface",
        "// (SIL Open Font License 1.1, see main/core/FONT_LICENSE.txt). Do not edit.",
        "",
        '#include "canvas.h"',
        "",
        "namespace {",
        "",
    ]
    accessors = []
    for name, file, size in FONTS:
        height, ascent, glyphs, bitmap = render_font(pathlib.Path(args.font_dir) / file, size)
        parts.append(emit(name, file, size, height, ascent, glyphs, bitmap))
        parts.append("")
        accessor = "font_" + name[len("kFont"):].lower()
        accessors.append(
            f"const Font &{accessor}()\n{{\n"
            f"    static const Font font = {{{height}, {ascent}, {name}Glyphs, {name}Bits}};\n"
            f"    return font;\n}}\n")

    parts.append("}  // namespace")
    parts.append("")
    parts.extend(accessors)
    pathlib.Path(args.out).write_text("\n".join(parts))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
